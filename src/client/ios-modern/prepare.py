"""Stage portable iOS assets and generate matching local-server deployment files.

Runs on Windows or macOS. Does not compile or start any service.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import zlib

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parents[1]
ASSETS = SOURCE / "server/ResourcesAndroid_Encrypt"
EXCLUDED = {".php", ".html", ".js", ".xls", ".xlsx", ".doc", ".docx", ".sql", ".pem", ".zip"}
ARCHIVES = {
    "curl-8.23.0.tar.xz": "8dadd7d2536a314f982ad05a651b713f426bf7d02cc2c76cffb9796f2218e6c5",
    "libwebp-1.6.0.tar.gz": "e4ab7009bf0629fd11982d4c2aa83964cf244cffba7347ecd39019a9e38c4564",
}
SOURCE_DIRS = ("Game/Classes", "Game/Platform", "Game/Protobuf", "cocos2dx", "CocosDenshion",
               "extensions", "external/sqlite3", "91lib/include", "libOS/include", "tinyxml",
               "protobuf-2.5.0rc1/src", "jsoncpp-src-0.5.0/include", "jsoncpp-src-0.5.0/src/lib_json",
               "scripting/lua/lua", "scripting/lua/tolua", "scripting/lua/cocos2dx_support")
CODE_SUFFIXES = {".c", ".cc", ".cpp", ".h", ".hpp", ".m", ".mm", ".inl", ".inc", ".pch"}


def stage_sources(destination):
    """Preserve original GBK files; give Apple Clang a UTF-8 copy of the source tree."""
    client = ROOT.parent
    converted = []
    for directory in SOURCE_DIRS:
        for path in (client / directory).rglob("*"):
            if not path.is_file() or path.suffix.lower() not in CODE_SUFFIXES:
                continue
            data = path.read_bytes()
            relative = path.relative_to(client)
            try:
                text = data.decode("utf-8-sig")
            except UnicodeDecodeError:
                text = data.decode("gb18030")
                converted.append(relative.as_posix())
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
    return converted


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", help="IPv4/DNS address reachable from the phone")
    parser.add_argument("--web-port", type=int, default=18081)
    parser.add_argument("--game-port", type=int, default=25524)
    parser.add_argument("--resource-version", default="1.78.6")
    parser.add_argument("--output", type=Path, default=ROOT / "generated")
    parser.add_argument("--web-root", type=Path, help="Dedicated public resource directory")
    parser.add_argument("--server-dir", type=Path, help="Optional server XML directory to update")
    parser.add_argument("--stage-only", action="store_true", help="Copy assets without deployment addresses")
    args = parser.parse_args()
    if not args.stage_only and not args.host:
        parser.error("--host is required unless --stage-only is selected")
    output = args.output.resolve()
    # Refuse to mix generated artifacts with unrelated user files.
    marker = output / ".onepiece-ios-generated"
    if output.exists() and any(output.iterdir()) and not marker.is_file():
        parser.error("output must be empty or previously generated by this script")
    output.mkdir(parents=True, exist_ok=True)
    marker.touch()
    for name, digest in ARCHIVES.items():
        path = ROOT / "vendor" / name
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            parser.error("missing or modified source archive: " + name)
    converted = stage_sources(output / "client")
    assets = output / "assets"
    assets.mkdir(exist_ok=True)
    count = 0
    for path in ASSETS.rglob("*"):
        if not path.is_file():
            continue
        relative = path.relative_to(ASSETS)
        if "summary_dzm" in relative.parts or path.suffix.lower() in EXCLUDED:
            continue
        if path.suffix.lower() == ".el":
            # A 32-bit precompiled Lua chunk cannot be loaded by the ARM64 interpreter.
            data = path.read_bytes()
            decoded = bytes(value ^ b"youaiABC"[index % 8] for index, value in enumerate(data))
            source = zlib.decompress(decoded[1:])
            if source.startswith((b"\x1bLua", b"\x1bLJ")):
                parser.error("supply Lua source instead of architecture-specific bytecode: " + str(relative))
        destination = assets / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
        count += 1
    web_root = (args.web_root or output / "web").resolve()
    if not args.stage_only:
        command = [sys.executable, str(SOURCE / "tools/configure_deployment.py"),
                   "--platform", "ios", "--ios-overlay", str(assets), "--host", args.host,
                   "--web-port", str(args.web_port), "--game-port", str(args.game_port),
                   "--resource-version", args.resource_version, "--web-root", str(web_root)]
        if args.server_dir:
            command += ["--server-dir", str(args.server_dir.resolve())]
        subprocess.run(command, check=True)
    else:
        (assets / "version_ios_local.cfg").unlink(missing_ok=True)
    (output / "preparation.json").write_text(json.dumps({
        "assets": count, "host": args.host if not args.stage_only else None,
        "webRoot": str(web_root) if not args.stage_only else None,
        "resourceVersion": args.resource_version, "stageOnly": args.stage_only,
        "compileVerified": False, "deviceVerified": False,
        "utf8ConvertedFiles": converted,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Staged", count, "client assets in", assets)
    if args.stage_only:
        print("Server address pending. Run again with --host before configuring Xcode.")


if __name__ == "__main__":
    main()
